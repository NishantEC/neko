//! rune-ui's copies are never edited by hand: every file the CLI wrote still has the hash `rune-ui.lock` recorded, and nothing
//! else was added among them. Fix a component upstream and run `rune-ui update`.

use sha2::{Digest, Sha256};

#[test]
fn no_copy_drifted_from_the_lock() {
    let root = env!("CARGO_MANIFEST_DIR");
    let lock = std::fs::read_to_string(format!("{root}/rune-ui.lock")).expect("rune-ui.lock");
    let mut listed = Vec::new();
    for line in lock.lines().map(str::trim).filter(|l| l.starts_with("{ target = ")) {
        let field = |name: &str| line.split(&format!("{name} = \"")).nth(1).and_then(|r| r.split('"').next()).unwrap().to_owned();
        let (target, want) = (field("target"), field("sha256"));
        let bytes = std::fs::read(format!("{root}/{target}")).unwrap_or_else(|_| panic!("{target} is in the lock but missing"));
        let got: String = Sha256::digest(&bytes).iter().map(|b| format!("{b:02x}")).collect();
        assert_eq!(got, want, "{target} was changed by hand; fix it upstream and run `rune-ui update`");
        listed.push(target);
    }
    assert!(listed.len() >= 20, "the lock lists the copies");
    fn files(dir: &std::path::Path, out: &mut Vec<std::path::PathBuf>) {
        for e in std::fs::read_dir(dir).unwrap().flatten() {
            if e.path().is_dir() { files(&e.path(), out) } else { out.push(e.path()) }
        }
    }
    let mut found = Vec::new();
    files(std::path::Path::new(&format!("{root}/src/ui")), &mut found);
    for f in found {
        let rel = f.strip_prefix(root).unwrap().to_string_lossy().into_owned();
        // `mod.rs` is regenerated by `rune-ui add` and not hashed.
        if rel != "src/ui/mod.rs" {
            assert!(listed.contains(&rel), "{rel} sits among rune-ui's copies but the lock does not know it");
        }
    }
}
