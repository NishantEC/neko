// from hushbacks packages/ui/src/components/charts/LineChart.tsx
import { type ChartConfig, ChartContainer, ChartTooltip, ChartTooltipContent } from "@/ui/chart";
import { CartesianGrid, LabelList, Line, type LineProps, LineChart as RechartsLineChart, XAxis, YAxis } from "recharts";

export interface LineChartProps {
  data: Record<string, unknown>[];
  dataKey: string;
  xKey: string;
  chartConfig: ChartConfig;
  emptyMessage?: string;
  className?: string;
  height?: string;
  // Optional axis customization
  xAxisProps?: {
    tickLine?: boolean;
    axisLine?: boolean;
    tickMargin?: number;
    tickFormatter?: (value: unknown) => string;
    angle?: number;
    textAnchor?: "start" | "middle" | "end" | "inherit";
    height?: number;
  };
  yAxisProps?: {
    tickLine?: boolean;
    axisLine?: boolean;
    tickMargin?: number;
    tickFormatter?: (value: unknown) => string;
    domain?: [number | string, number | string];
  };
  // Optional line customization
  lineProps?: Partial<LineProps>;
  // Optional tooltip customization
  showTooltip?: boolean;
  tooltipFormatter?: (value: unknown, name: string, props: unknown) => [string, string];
  // Optional label list customization
  showLabels?: boolean;
  labelListProps?: {
    position?: "top" | "bottom" | "left" | "right" | "inside" | "outside";
    offset?: number;
    className?: string;
    fontSize?: number;
  };
  // Optional chart customization
  accessibilityLayer?: boolean;
  margin?: {
    top?: number;
    right?: number;
    bottom?: number;
    left?: number;
  };
  cartesianGridProps?: {
    vertical?: boolean;
    strokeDasharray?: string;
    className?: string;
  };
}

export function LineChart({
  data,
  dataKey,
  xKey,
  chartConfig,
  emptyMessage = "No data available",
  className = "h-64",
  height,
  xAxisProps = {},
  yAxisProps = {},
  lineProps = {},
  showTooltip = true,
  tooltipFormatter,
  showLabels = false,
  labelListProps = {},
  accessibilityLayer = false,
  margin = {
    top: 20,
    left: 12,
    right: 12,
  },
  cartesianGridProps = {},
}: LineChartProps) {
  if (!data || data.length === 0) {
    return <div className={`flex items-center justify-center ${className} text-muted-foreground`}>{emptyMessage}</div>;
  }

  const defaultXAxisProps = {
    tickLine: false,
    axisLine: false,
    tickMargin: 8,
    ...xAxisProps,
  };

  const defaultYAxisProps = {
    tickLine: false,
    axisLine: false,
    tickMargin: 8,
    ...yAxisProps,
  };

  const defaultCartesianGridProps = {
    vertical: false,
    strokeDasharray: "3 3",
    className: "stroke-muted",
    ...cartesianGridProps,
  };

  // Always use the CSS variable generated by ChartStyle
  // The ChartStyle component generates --color-{key} variables from the chartConfig
  const color = `var(--color-${dataKey})`;
  const defaultLineProps = {
    type: "natural" as const,
    strokeWidth: 2,
    dot: { fill: color },
    activeDot: { r: 6 },
    ...lineProps,
  };

  const defaultLabelListProps = {
    position: "top" as const,
    offset: 12,
    className: "fill-foreground",
    fontSize: 12,
    ...labelListProps,
  };

  return (
    <ChartContainer config={chartConfig} className={className} style={height ? { height } : undefined}>
      <RechartsLineChart accessibilityLayer={accessibilityLayer} data={data} margin={margin}>
        <CartesianGrid {...defaultCartesianGridProps} />
        {/* @ts-ignore - recharts type definitions issue with textAnchor */}
        <XAxis dataKey={xKey} className="text-xs" {...defaultXAxisProps} />
        <YAxis className="text-xs" {...defaultYAxisProps} />
        {showTooltip && (
          <ChartTooltip
            cursor={false}
            content={<ChartTooltipContent indicator="line" />}
            formatter={tooltipFormatter}
          />
        )}
        {showLabels ? (
          // @ts-expect-error - recharts type definitions issue with LabelList children
          <Line dataKey={dataKey} stroke={color} {...defaultLineProps}>
            <LabelList {...defaultLabelListProps} />
          </Line>
        ) : (
          // @ts-expect-error - recharts type definitions issue
          <Line dataKey={dataKey} stroke={color} {...defaultLineProps} />
        )}
      </RechartsLineChart>
    </ChartContainer>
  );
}
