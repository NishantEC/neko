#!/usr/bin/env node
// Writes src/themes/builtin.generated.css from the built-in theme data
// (src/themes/builtin/*.json), using the same derive.js the page uses. The vite
// build runs it on every build (vite.config.ts), so the stylesheet cannot go
// stale; the file is committed so a plain checkout type-checks, and
// scripts/verify/themes.mjs fails if the committed copy differs.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { themesCss } from "../src/themes/derive.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/themes");

export function builtinThemes() {
  return readdirSync(path.join(root, "builtin"))
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => JSON.parse(readFileSync(path.join(root, "builtin", f), "utf8")));
}

const HEADER = "/* Generated by web/scripts/themes.mjs from src/themes/builtin/*.json. Do not edit: change the JSON. */\n";

export function builtinCss() {
  return HEADER + themesCss(builtinThemes());
}

export function writeBuiltinCss() {
  const file = path.join(root, "builtin.generated.css");
  const css = builtinCss();
  let current = "";
  try { current = readFileSync(file, "utf8"); } catch { /* first run */ }
  if (current !== css) writeFileSync(file, css);
  return file;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) console.log("wrote", writeBuiltinCss());
